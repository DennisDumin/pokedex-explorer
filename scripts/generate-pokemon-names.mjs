import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_COMMIT = 'fe7aa9347f9a7a0c86f6a07187785f2a6f91b12d';
const SOURCE_URL = `https://raw.githubusercontent.com/PokeAPI/pokeapi/${SOURCE_COMMIT}/data/v2/csv/pokemon_species_names.csv`;
const GERMAN_LANGUAGE_ID = 6;
const FIRST_SPECIES_ID = 1;
const LAST_SPECIES_ID = 1025;

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(scriptDirectory, '../src/data/pokemon-names-de.js');

function parseCsv(csv) {
  const rows = [];
  let field = '';
  let row = [];
  let insideQuotes = false;

  for (let index = 0; index < csv.length; index += 1) {
    const character = csv[index];

    if (insideQuotes) {
      if (character === '"' && csv[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        insideQuotes = false;
      } else {
        field += character;
      }
      continue;
    }

    if (character === '"') {
      insideQuotes = true;
    } else if (character === ',') {
      row.push(field);
      field = '';
    } else if (character === '\n') {
      row.push(field.replace(/\r$/, ''));
      rows.push(row);
      field = '';
      row = [];
    } else {
      field += character;
    }
  }

  if (insideQuotes) throw new TypeError('The source CSV contains an unclosed quote.');

  if (field !== '' || row.length > 0) {
    row.push(field.replace(/\r$/, ''));
    rows.push(row);
  }

  return rows;
}

function findColumnIndex(header, columnName) {
  const index = header.indexOf(columnName);

  if (index === -1) {
    throw new TypeError(`The source CSV is missing the ${columnName} column.`);
  }

  return index;
}

function createGermanNameMap(csv) {
  const [header = [], ...rows] = parseCsv(csv.replace(/^\uFEFF/, ''));
  const speciesIdColumn = findColumnIndex(header, 'pokemon_species_id');
  const languageIdColumn = findColumnIndex(header, 'local_language_id');
  const nameColumn = findColumnIndex(header, 'name');
  const names = Array(LAST_SPECIES_ID + 1).fill(null);

  for (const row of rows) {
    if (Number(row[languageIdColumn]) !== GERMAN_LANGUAGE_ID) continue;

    const speciesId = Number(row[speciesIdColumn]);
    if (speciesId < FIRST_SPECIES_ID || speciesId > LAST_SPECIES_ID) continue;

    const name = row[nameColumn]?.trim();
    if (!Number.isSafeInteger(speciesId) || !name) {
      throw new TypeError(
        `Invalid German name entry for species ${row[speciesIdColumn]}.`,
      );
    }
    if (names[speciesId] !== null) {
      throw new TypeError(`Duplicate German name entry for species ${speciesId}.`);
    }

    names[speciesId] = name;
  }

  const missingSpeciesIds = [];

  for (let speciesId = FIRST_SPECIES_ID; speciesId <= LAST_SPECIES_ID; speciesId += 1) {
    if (names[speciesId] === null) missingSpeciesIds.push(speciesId);
  }

  if (missingSpeciesIds.length > 0) {
    throw new TypeError(
      `Missing German names for species: ${missingSpeciesIds.join(', ')}.`,
    );
  }

  return names;
}

function createModule(names) {
  return `// Generated by scripts/generate-pokemon-names.mjs. Do not edit manually.\n// Source: ${SOURCE_URL}\n// PokéAPI data is distributed under the BSD 3-Clause License.\n\n// prettier-ignore\nconst pokemonNamesDe = Object.freeze(${JSON.stringify(names)});\n\nexport { pokemonNamesDe };\n`;
}

async function generatePokemonNames() {
  const response = await globalThis.fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(
      `Unable to download PokéAPI names (${response.status} ${response.statusText}).`,
    );
  }

  const names = createGermanNameMap(await response.text());
  const output = createModule(names);

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, 'utf8');

  const byteLength = new globalThis.TextEncoder().encode(output).byteLength;
  globalThis.console.log(
    `Generated ${path.relative(path.resolve(scriptDirectory, '..'), outputPath)} with ${LAST_SPECIES_ID} names (${byteLength} bytes).`,
  );
}

await generatePokemonNames();
